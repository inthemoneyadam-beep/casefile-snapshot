// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main(): Promise<void> {
  // 1. The content: a quote or attribute set that does not check out stops
  //    the run here, before anything touches the data directory.
  const checked = checkContent();
  if (checked.problems.length) {
    console.error('seed: the synthetic content does not check out; nothing was written:');
    for (const p of checked.problems) console.error(`  - ${p}`);
    process.exit(1);
  }

  // 2. Where it would write. The default directory is where the real case lives.
  const target = config.dataDir;
  const isDefaultDir = samePathKey(target) === samePathKey(path.join(projectRoot, 'data'));
  console.log(`seed: target data directory ${target}${isDefaultDir ? ' (the default case directory)' : ''}`);
  if (isDefaultDir && !args.force) {
    console.error(
      'seed: refusing to write into the default case directory. Point CASEFILE_DATA_DIR at a scratch directory, for example\n' +
        '  CASEFILE_DATA_DIR=./data-demo npm run seed -- --passphrase "..."\n' +
        'or pass --force if this directory is a throwaway. Even with --force it is refused once it holds any case records.',
    );
    process.exit(1);
  }

  // 3. The PDFs, in memory: everything written after this is synchronous.
  const pdfs = new Map<SeedDoc['key'], Buffer>();
  for (const sd of DOCS) pdfs.set(sd.key, await makePdf(sd.pages));

  // 4. Unlock.
  ensureDirs();
  let created = false;
  if (!keyringExists(config.dataDir)) {
    createKeyring(config.dataDir, passphrase).fill(0);
    created = true;
    console.log(`seed: no keyring in ${config.dataDir}; created one with the given passphrase.`);
  }
  let dek: Buffer;
  try {
    dek = unlockKeyring(config.dataDir, passphrase);
  } catch (err) {
    if (err instanceof WrongPassphraseError) {
      console.error('seed: wrong passphrase for this data directory.');
      process.exit(1);
    }
    throw err;
  }
  try {
    openDatabase(deriveSubkey(dek, 'casefile/db'));
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error(/not a database/i.test(msg) ? 'seed: wrong passphrase for this database.' : `seed: could not open the database: ${msg}`);
    process.exit(1);
  }
  setFileKey(deriveSubkey(dek, 'casefile/files'));
  dek.fill(0);

  // 5. Only into an empty case, unless --force; never into a default
  //    directory that holds records.
  const inUse = caseRowCounts().filter((c) => c.n > 0);
  if (inUse.length) {
    const list = inUse.map((c) => `${c.n} ${c.table}`).join(', ');
    const refusal = isDefaultDir
      ? `seed: ${target} is the default case directory and already holds case records (${list}). The seed never adds synthetic records to it, even with --force; use a scratch CASEFILE_DATA_DIR.`
      : !args.force
        ? `seed: ${target} already holds case records (${list}). The synthetic case is only written into an empty case. Re-run with --force to add it next to those records anyway.`
        : null;
    if (refusal) {
      console.error(refusal);
      closeDatabase();
      setFileKey(null);
      process.exit(1);
    }
    console.warn(`seed: --force: adding the synthetic case next to existing records (${list}).`);
  }

  // 6. The encrypted PDFs first (a file write cannot be rolled back, and a
  //    file no row points at is harmless), then every row in one transaction:
  //    a failure leaves the database exactly as it was.
  const storageKeys: Record<SeedDoc['key'], string> = { consult: '', labs: '', mri: '', letter: '' };
  for (const sd of DOCS) storageKeys[sd.key] = putFile(pdfs.get(sd.key)!, sd.filename);
  let summary: string[];
  try {
    summary = db().transaction(() => writeCase(checked.facts, pdfs, storageKeys));
  } catch (err) {
    console.error('seed: the database write failed and was rolled back; no rows were added.');
    console.error(`seed: the ${DOCS.length} synthetic PDFs stored just before are referenced by nothing and were left in place (safe to remove by hand):`);
    for (const k of Object.values(storageKeys)) console.error(`  ${path.join(config.filesDir, k)}`);
    throw err;
  }

  closeDatabase();
  setFileKey(null);

  console.log(`seed: synthetic case written to ${config.dataDir}${created ? ' (new keyring created)' : ''}`);
  for (const line of summary) console.log(`  - ${line}`);
  console.log('Every name and value is invented. Unlock with the same passphrase and open Timeline, Documents, Facts or Records to look around.');
}

main().catch((err) => {
  console.error('seed failed:', err instanceof Error ? err.message : err);
  try {
    closeDatabase();
    setFileKey(null);
  } catch {
    // ignore
  }
  process.exit(1);
});
