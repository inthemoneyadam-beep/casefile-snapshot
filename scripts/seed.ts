// ---------------------------------------------------------------------------
// Checks made before anything is written
// ---------------------------------------------------------------------------
interface CheckedFact {
  fact: SeedFact;
  /** The attribute set as validateAttributes normalised it. */
  attributes: Record<string, unknown>;
  /** Offset of the quote in its page text. */
  at: number;
}

/** Every attribute set and citation quote checked against the content, before any I/O. */
function checkContent(): { facts: CheckedFact[]; problems: string[] } {
  const pages = new Map<string, string>();
  for (const sd of DOCS) sd.pages.forEach((lines, i) => pages.set(`${sd.key}:${i + 1}`, lines.join('\n')));
  const facts: CheckedFact[] = [];
  const problems: string[] = [];
  for (const f of FACTS) {
    const v = validateAttributes(f.type, f.attributes);
    if (!v.ok) problems.push(`invalid attributes for ${f.type} "${f.statement}": ${v.error}`);
    const text = pages.get(`${f.doc}:${f.page}`);
    const at = text === undefined ? -1 : text.indexOf(f.quote);
    if (text === undefined) problems.push(`no page ${f.page} in ${f.doc} for "${f.statement}"`);
    else if (at < 0) problems.push(`quote not found verbatim on ${f.doc} page ${f.page}: "${f.quote}"`);
    if (v.ok && at >= 0) facts.push({ fact: f, attributes: v.value, at });
  }
  return { facts, problems };
}

/** A path as the file system knows it, for comparing two spellings of one directory. */
function samePathKey(p: string): string {
  let r = path.resolve(p);
  try {
    r = fs.realpathSync.native(r);
  } catch {
    // Not created yet: the resolved path is all there is.
  }
  return process.platform === 'win32' ? r.toLowerCase() : r;
}

