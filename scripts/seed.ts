function plusDays(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return todayIso(d);
}

function partial(text: string): { iso: string | null; precision: string; text: string } {
  const p = parsePartialDate(text);
  return { iso: p.iso, precision: p.precision, text };
}

async function makePdf(pages: string[][]): Promise<Buffer> {
  const pdf = await PDFDocument.create();
  pdf.setTitle('Synthetic Casefile seed document');
  pdf.setProducer('Casefile seed');
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  for (const lines of pages) {
    const page = pdf.addPage([612, 792]);
    let y = 752;
    for (const line of lines) {
      page.drawText(line, { x: 48, y, size: 10, font });
      y -= 14;
    }
  }
  return Buffer.from(await pdf.save());
}

